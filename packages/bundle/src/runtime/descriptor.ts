import { z } from 'zod';

import { contractIdPattern } from '../contracts/ids.js';
import { semverString } from './manifest.js';

export const descriptorKinds = [
  'service',
  'hooks',
  'event',
  'command',
  'settings',
  'storage-type',
] as const;

export type DescriptorKind = (typeof descriptorKinds)[number];

export const descriptorEntrySchema = z
  .object({
    id: z.string().regex(contractIdPattern),
    version: semverString,
    kind: z.enum(descriptorKinds),
    environment: z.enum(['host', 'desktopMain', 'client']),
    cardinality: z.enum(['one', 'many']),
    local: z.boolean(),
    /** Path relative to the bundle's dist, e.g. "schemas/hooks/v1.json". */
    schema: z.string(),
  })
  .strict();

export type DescriptorEntry = z.output<typeof descriptorEntrySchema>;

/** `dist/contracts.json`: every provided contract per environment, generated by the build. */
export const descriptorSchema = z
  .object({
    descriptorVersion: z.literal(1),
    bundle: z.object({ id: z.string(), version: semverString }).strict(),
    contracts: z.array(descriptorEntrySchema),
  })
  .strict();

export type Descriptor = z.output<typeof descriptorSchema>;

export const parseDescriptor = (document: unknown): Descriptor =>
  descriptorSchema.parse(document);

/** The empty descriptor a converted v0 manifest receives. */
export const emptyDescriptor = (id: string, version: string): Descriptor => ({
  descriptorVersion: 1,
  bundle: { id, version },
  contracts: [],
});

import type { TokenSet, Tokens } from './tokens.js';

/** The variables every window gets before its shell applies its own chrome. */
export const windowVariables = (tokens: Tokens): TokenSet => ({
  '--doric-titlebar-height': `${tokens.window.titlebarHeight}px`,
  '--doric-window-background': 'var(--background)',
  '--doric-safe-top': '0px',
  '--doric-safe-left': '0px',
  '--doric-safe-right': '0px',
});

const declarations = (set: TokenSet): string =>
  Object.entries(set)
    .map(([name, value]) => `  ${name}: ${value};\n`)
    .join('');

/**
 * `tokens.css`: the light palette and the shared tokens on `:root`, the dark
 * palette on `.dark`, and the window variables, exactly as the stylesheet the
 * shell loads states them.
 */
export const tokensCss = (tokens: Tokens): string =>
  '/* Generated by packages/desktop-ui/scripts/build-tokens.mjs from\n' +
  '   src/tokens/tokens.ts. Do not edit; edit the tokens and rebuild. */\n\n' +
  `:root {\n${declarations(tokens.variants.light)}${declarations(tokens.shared)}}\n\n` +
  `.dark {\n${declarations(tokens.variants.dark)}}\n\n` +
  `:root {\n${declarations(windowVariables(tokens))}}\n`;

/**
 * The CSS variables a window of the given variant resolves: that variant's
 * palette, the shared tokens and the window variables.
 */
export const resolvedVariables = (
  tokens: Tokens,
  variant: keyof Tokens['variants'] = tokens.defaultVariant,
): Readonly<Record<string, string>> => ({
  ...tokens.shared,
  ...tokens.variants[variant],
  ...windowVariables(tokens),
});

// Writes `src/sandbox/shim-names.ts` (D13) from the installed packages: the
// export names of each namespace a library's shims read, the SHA-256 of
// those lists (`SHIM_ABI`, the library module's `papercraftAbi`), and
// react-ui's library components plus papercraft's `Export`. Run it after any
// of these packages changes; PC28 checks the committed file against it.
//
//   node bundles/features/papercraft/scripts/shim-names.mjs

import { createHash } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

const namespaces = {
  reactLang: await import('@openuidev/react-lang'),
  langCore: await import('@openuidev/lang-core'),
  zod: await import('zod'),
  zodCore: await import('zod/v4/core'),
};
const { openuiLibrary } = await import('@openuidev/react-ui');

const sorted = (names) => [...new Set(names)].sort();

const shimNames = Object.fromEntries(
  Object.entries(namespaces).map(([key, namespace]) => [
    key,
    sorted(Object.keys(namespace)),
  ]),
);
const builtins = sorted([...Object.keys(openuiLibrary.components), 'Export']);
const abi = createHash('sha256')
  .update(JSON.stringify(shimNames))
  .digest('hex');

const list = (names, indent) =>
  names.map((name) => `${indent}'${name}',`).join('\n');

const text = `// Generated by \`scripts/shim-names.mjs\` from the installed react-ui,
// react-lang, lang-core and zod. Do not edit: run the script again when one
// of them changes (PC28).

/** react-ui's library components plus papercraft's \`Export\` (D11). */
export const BUILTIN_COMPONENT_NAMES: readonly string[] = [
${list(builtins, '  ')}
];

/** The exports of each shimmed namespace (D13). */
export const SHIM_NAMES = {
${Object.entries(shimNames)
  .map(([key, names]) => `  ${key}: [\n${list(names, '    ')}\n  ],`)
  .join('\n')}
} as const;

/** The SHA-256 of \`SHIM_NAMES\` as JSON: the library module's \`papercraftAbi\`. */
export const SHIM_ABI =
  '${abi}';
`;

await writeFile(new URL('../src/sandbox/shim-names.ts', import.meta.url), text);
